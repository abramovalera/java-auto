function keyPatterns(k) {
  if (k.startsWith("tpl:")) return [new RegExp(`<code>${reEsc(k.slice(4))}</code>`)];
  const parts = k.split("+");
  return [
    new RegExp(parts.map((p) => `<kbd>${reEsc(p)}</kbd>`).join("\\s*\\+\\s*")),
    new RegExp(`(^|[^\\w+])${reEsc(k)}(?![\\w+])`),
  ];
}
