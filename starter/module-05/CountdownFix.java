// Задача 3: обратный отсчёт перед стартом ракеты.
// Программа должна вывести 10, 9, 8, …, 1 (каждое число на своей строке) и «Пуск!».
// Её писали в спешке. Найди и исправь ошибки — не переписывай всё заново.
// Осторожно: если запустишь как есть, программа не остановится сама.
// Останови её красным квадратом Stop в панели Run (или Ctrl+F2).
public class CountdownFix {
    public static void main(String[] args) {
        int i = 10;
        while (i >= 0) {
            System.out.println(i);
        }
        System.out.println("Пуск!");
    }
}
